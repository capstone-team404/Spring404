import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../frontend/src/mapInteractions.js', import.meta.url), 'utf8');
const { observeMapTaps, touchToPosition, zoneAtPosition, readLatLng } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
let time = 0;
const element = new EventTarget();
const received = [];
const taps = observeMapTaps(element, point => received.push(point), () => time);
const finger = (x = 100, y = 100, identifier = 1) => ({ clientX: x, clientY: y, identifier });
const send = (type, touches, changedTouches = []) => {
  const event = new Event(type);
  Object.defineProperties(event, { touches: { value: touches }, changedTouches: { value: changedTouches } });
  element.dispatchEvent(event);
};
const begin = () => { time += 1000; send('touchstart', [finger()]); };
begin(); time += 100; send('touchend', [], [finger(102, 104)]);
assert.equal(received.length, 1, 'Short single-finger tap selects once');
assert.equal(taps.ignoreSyntheticClick(), true, 'Synthetic SDK click must not duplicate the tap');
time += 900; assert.equal(taps.ignoreSyntheticClick(), false, 'Mouse clicks resume');
begin(); send('touchmove', [finger(140, 100)]); send('touchmove', [finger()]); send('touchend', [], [finger()]);
assert.equal(received.length, 1, 'Drag out and back must not select');
begin(); send('touchstart', [finger(), finger(120, 120, 2)]); send('touchend', [finger()], [finger(120, 120, 2)]); send('touchend', [], [finger()]);
assert.equal(received.length, 1, 'Pinch and second-finger release must not select');
begin(); time += 700; send('touchend', [], [finger()]);
assert.equal(received.length, 1, 'Long press must not select');
begin(); send('touchcancel', [], [finger()]); send('touchend', [], [finger()]);
assert.equal(received.length, 1, 'Cancelled gesture must not select');
taps.dispose(); begin(); send('touchend', [], [finger()]);
assert.equal(received.length, 1, 'Unmount removes all listeners');

const bounds = { getNorthEast: () => ({ lat: () => 37.56, lng: () => 126.93 }), getSouthWest: () => ({ lat: () => 37.55, lng: () => 126.92 }) };
const map = { getBounds: () => bounds };
const container = { getBoundingClientRect: () => ({ left: 20, top: 30, width: 400, height: 800 }) };
const point = touchToPosition(map, container, { clientX: 220, clientY: 430 });
assert.ok(Math.abs(point.lng - 126.925) < 1e-9);
assert.ok(Math.abs(point.lat - 37.555) < 1e-6);
assert.equal(touchToPosition(map, container, { clientX: 0, clientY: 430 }), null);
assert.equal(touchToPosition(map, container, {}), null);
assert.equal(touchToPosition({}, container, { clientX: 220, clientY: 430 }), null);
assert.deepEqual(readLatLng({ _lat: 0, _lng: 0 }), { lat: 0, lng: 0 });
const zones = [{ zone_id: 1, min_lat: 37.55, max_lat: 37.56, min_lng: 126.92, max_lng: 126.93 }];
assert.equal(zoneAtPosition(zones, point).zone_id, 1);
assert.equal(zoneAtPosition(zones, { lat: 37.56, lng: 126.925 }), undefined);
console.log('PASS: touch selection, synthetic click deduplication, drag/pinch/long press/cancel, cleanup, projected coordinates and zone boundaries.');
